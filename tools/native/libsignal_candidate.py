#!/usr/bin/env python3
"""Prepare a pinned libsignal upgrade without changing accepted binary locks."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import sys
import tempfile

import prepare_sources
import stage_artifacts


class Failure(Exception):
    pass


def require(value, message):
    if not value:
        raise Failure(message)


def load(candidate_path, lock_path):
    candidate_path = candidate_path.resolve(strict=True)
    lock_path = lock_path.resolve(strict=True)
    value = json.loads(candidate_path.read_text())
    fields = {'schema', 'kind', 'status', 'release_allowed', 'base_lock_sha256',
              'source_commit', 'prepared_tree', 'input_version', 'output_version', 'patch'}
    require(isinstance(value, dict) and set(value) == fields, 'Unexpected source candidate fields')
    require(type(value['schema']) is int and value['schema'] == 1 and
            value['kind'] == 'collie-libsignal-source-candidate' and
            value['status'] == 'SOURCE_ONLY' and value['release_allowed'] is False,
            'Candidate must remain source-only and cannot authorize release')
    require(stage_artifacts.digest(lock_path) == value['base_lock_sha256'],
            'Candidate does not extend the selected accepted native lock')
    stage_artifacts.load_lock(lock_path)
    for key in ('source_commit', 'prepared_tree'):
        require(isinstance(value[key], str) and re.fullmatch('[0-9a-f]{40}', value[key]),
                'Invalid candidate source pin')
    version = value['input_version']
    require(isinstance(version, str) and re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version),
            'Invalid candidate input version')
    require(isinstance(value['output_version'], str) and
            re.fullmatch(re.escape(version) + r'-collie\.[1-9][0-9]*', value['output_version']),
            'Candidate output must use a distinct versioned Collie coordinate')
    item = value['patch']
    require(isinstance(item, dict) and set(item) == {'path', 'sha256'} and
            item['path'] == f'patches/libsignal-{version}-attributed.mbox',
            'Unexpected candidate patch path')
    patch = stage_artifacts.safe_file(candidate_path.parent, candidate_path.parent / item['path'])
    require(stage_artifacts.digest(patch) == item['sha256'], 'Candidate patch hash differs')
    return value


def replay_tree(repo, candidate, candidate_path, temporary_parent):
    """Reapply mailbox diffs from the upstream commit in an independent index."""
    git = prepare_sources.git
    object_dir = git(repo, 'rev-parse', '--path-format=absolute', '--git-path', 'objects')
    with tempfile.TemporaryDirectory(prefix='libsignal-candidate-proof-', dir=temporary_parent) as temp:
        root = Path(temp)
        (root / 'objects').mkdir()
        environment = {'GIT_INDEX_FILE': str(root / 'index'),
                       'GIT_OBJECT_DIRECTORY': str(root / 'objects'),
                       'GIT_ALTERNATE_OBJECT_DIRECTORIES': object_dir}
        git(repo, 'read-tree', candidate['source_commit'], extra_env=environment)
        data = (candidate_path.parent / candidate['patch']['path']).read_bytes()
        parts = [part for part in re.split(
            rb'(?=^From [0-9a-f]{40} Mon Sep 17 00:00:00 2001$)', data, flags=re.M) if part.strip()]
        require(bool(parts), 'Candidate mailbox is empty')
        for part in parts:
            git(repo, 'apply', '--cached', '--binary', '--whitespace=nowarn',
                data=part, extra_env=environment)
        return git(repo, 'write-tree', extra_env=environment)


def check_extra_inputs(repo, allow_generated=False):
    """Ignored files are build inputs too; only the post-build pass permits outputs."""
    exclude = Path(prepare_sources.git(repo, 'rev-parse', '--path-format=absolute', '--git-path', 'info/exclude'))
    require(not os.path.lexists(exclude) or
            (exclude.is_file() and not exclude.is_symlink() and exclude.stat().st_size == 0),
            'Candidate source cannot use local Git exclude rules')
    generated = ('target/', 'java/.gradle/', 'java/.kotlin/', 'java/build/',
                 'java/android/build/', 'java/client/build/', 'java/server/build/',
                 'java/backup-tool/build/', 'java/android/src/main/jniLibs/',
                 'java/android/src/main/assets/acknowledgments/')
    # No --exclude-standard: this includes ignored files as well as ordinary
    # untracked files. local.properties and client/shared resource JNI are not
    # generated by the Android-only build and are never allowed.
    for raw in prepare_sources.git(repo, 'ls-files', '--others', '-z', raw=True).split(b'\0'):
        if not raw:
            continue
        name = os.fsdecode(raw)
        require(allow_generated and name.startswith(generated),
                'Candidate contains unreviewed input: ' + name)


def verify_prepared(candidate_path, lock_path, source_root, allow_generated=False):
    candidate_path = candidate_path.resolve(strict=True)
    candidate = load(candidate_path, lock_path)
    source_root = source_root.resolve(strict=True)
    repo = source_root / 'libsignal'
    require(repo.is_dir() and not repo.is_symlink(), 'Candidate source is missing or a symlink')
    git = prepare_sources.git
    top_level = git(repo, 'rev-parse', '--show-toplevel', raw=True).removesuffix(b'\n')
    require(Path(os.fsdecode(top_level)).resolve(strict=True) == repo,
            'Candidate Git worktree differs from the build directory')
    require(git(repo, 'cat-file', '-t', candidate['source_commit']) == 'commit',
            'Candidate upstream commit is unavailable')
    prepare_sources.verify_worktree(repo)
    check_extra_inputs(repo, allow_generated=allow_generated)
    expected = replay_tree(repo, candidate, candidate_path, source_root.parent)
    require(expected == candidate['prepared_tree'], 'Candidate replay differs from the pinned source tree')
    require(git(repo, 'write-tree') == expected and git(repo, 'rev-parse', 'HEAD^{tree}') == expected,
            'Prepared candidate differs from the reviewed source tree')
    require(not git(repo, 'diff', '--name-only'), 'Prepared candidate has unexpected source changes')
    lock = stage_artifacts.load_lock(lock_path.resolve(strict=True))
    require((repo / 'rust-toolchain').read_text().strip() == lock['toolchain_reference']['rust_version'],
            'Candidate Rust version differs from the pinned toolchain')
    require(re.search(r'^\s*version\s*=\s*"' + re.escape(candidate['input_version']) + r'"\s*$',
                      (repo / 'java/build.gradle').read_text(), flags=re.M),
            'Candidate Java artifact version differs')
    return {'schema': 1, 'scope': 'libsignal candidate source only; build and runtime unverified',
            'release_allowed': False, 'candidate_sha256': stage_artifacts.digest(candidate_path),
            'lock_sha256': stage_artifacts.digest(lock_path),
            'sources': {'libsignal': {'base': candidate['source_commit'], 'prepared_tree': expected}}}


def prepare(candidate_path, lock_path, repository, output):
    candidate_path = candidate_path.resolve(strict=True)
    candidate = load(candidate_path, lock_path)
    repository = repository.resolve(strict=True)
    output = output.absolute()
    require(not os.path.lexists(output), 'Candidate source output already exists')
    git = prepare_sources.git
    require(git(repository, 'cat-file', '-t', candidate['source_commit']) == 'commit',
            'Candidate upstream commit is unavailable')
    output.mkdir(parents=True)
    try:
        repo = output / 'libsignal'
        repo.mkdir()
        git(repo, 'init', '--quiet', '--template=')
        git(repo, 'fetch', '--quiet', '--no-tags', '--depth=1', str(repository), candidate['source_commit'])
        git(repo, 'checkout', '--quiet', '--detach', 'FETCH_HEAD')
        git(repo, 'am', '--3way', str(candidate_path.parent / candidate['patch']['path']))
        proof = verify_prepared(candidate_path, lock_path, output)
        (output / 'source-receipt.json').write_text(json.dumps(proof, indent=2, sort_keys=True) + '\n')
        return proof
    except Exception:
        shutil.rmtree(output)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--candidate', required=True, type=Path)
    parser.add_argument('--lock', required=True, type=Path)
    parser.add_argument('--libsignal', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--verify-prepared', action='store_true')
    args = parser.parse_args()
    try:
        if args.verify_prepared:
            result = verify_prepared(args.candidate, args.lock, args.output)
        else:
            require(args.libsignal is not None, 'A local libsignal repository is required')
            result = prepare(args.candidate, args.lock, args.libsignal, args.output)
    except (Failure, prepare_sources.Failure, stage_artifacts.Failure, OSError, ValueError) as exc:
        print(f'libsignal candidate preparation failed: {exc}', file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
